import unreal
levels=unreal.get_editor_subsystem(unreal.LevelEditorSubsystem)
actors=unreal.get_editor_subsystem(unreal.EditorActorSubsystem)
assert levels.load_level('/Game/TroubleSquad/Maps/L_SubterraneanLab')
vol=next((a for a in actors.get_all_level_actors() if a.get_actor_label()=='Lab Reference Exposure'),None)
if vol is None: vol=actors.spawn_actor_from_class(unreal.PostProcessVolume,unreal.Vector(0,0,0));vol.set_actor_label('Lab Reference Exposure')
vol.set_editor_property('unbound',True)
vol.set_editor_property('priority',100)
s=vol.get_editor_property('settings')
s.set_editor_property('override_auto_exposure_method',True)
s.set_editor_property('auto_exposure_method',unreal.AutoExposureMethod.AEM_MANUAL)
s.set_editor_property('override_auto_exposure_apply_physical_camera_exposure',True)
s.set_editor_property('auto_exposure_apply_physical_camera_exposure',False)
s.set_editor_property('override_auto_exposure_bias',True)
s.set_editor_property('auto_exposure_bias',0.0)
vol.set_editor_property('settings',s)
assert levels.save_current_level()
unreal.log('LAB_EXPOSURE_FIXED')
